/**
 * scaffold_ios_app — create a complete, buildable iOS project in one call.
 *
 * `write_file` can produce Swift but not the rest of an app: `.plist` and entitlements are
 * refused on purpose (macOS and Xcode pick those up by themselves), and a `.pbxproj` is a
 * machine-generated format no model should be hand-writing. So the agent could emit sources
 * that no project referenced.
 *
 * ## How this stays inside the same fence
 *
 *   - The model supplies VALUES (a name, a bundle id, a deployment target, a few usage
 *     strings), never file content. Every file is written from a fixed template in this
 *     module, so there is no path by which this tool writes an arbitrary plist.
 *   - Every value is validated against a conservative pattern before it touches a template;
 *     free text (usage descriptions) is emitted as a JSON string, which is valid YAML.
 *   - The `.xcodeproj` is generated by XcodeGen from the `project.yml` this tool wrote, run
 *     with a FIXED argv and no shell. Info.plist and the entitlements file come out of
 *     XcodeGen's `info:`/`entitlements:` blocks, not out of anything the model typed.
 *   - Same WHERE gate as write_file (`policy.fs.writableDirs`, no hidden segments, symlinks
 *     resolved). It refuses to run in a folder that already holds a project, so it can only
 *     ever CREATE: classified reversible, nothing is overwritten, delete the folder to undo.
 *
 * After scaffolding, further Swift goes in with write_file, and `project.yml` (the source of
 * truth — it is a `.yml`, already writable) is edited to add files, targets or capabilities,
 * then the project is regenerated by calling this tool's `regenerate` mode.
 */
import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

import { recordDeliverable } from "../deliverables.ts";
import type { ClassifiedAction, Policy, PolicyDecision, Tool } from "../types.ts";
import { resolveArg, textTargetGate } from "./write-file.ts";

interface Args {
  bundle_id?: string;
  /** Existing project folder to re-run XcodeGen in, after project.yml was edited. */
  dir?: string;
  deployment_target?: string;
  display_name?: string;
  mode?: string;
  name?: string;
  /** Adds the aps-environment entitlement. Needs a paid team to sign. */
  push?: boolean;
  team_id?: string;
  tests?: boolean;
  /** Info.plist usage strings, e.g. { "NSCameraUsageDescription": "Scan receipts" }. */
  usage?: Record<string, string>;
}

const NAME = /^[A-Za-z][A-Za-z0-9]{0,39}$/;
const BUNDLE = /^[A-Za-z][A-Za-z0-9-]*(\.[A-Za-z][A-Za-z0-9-]*){1,5}$/;
const TARGET = /^\d{1,2}\.\d{1,2}$/;
const TEAM = /^[A-Z0-9]{10}$/;

/** The only Info.plist keys the model may set. All are human-readable permission prompts. */
const USAGE_KEYS = new Set([
  "NSCameraUsageDescription",
  "NSContactsUsageDescription",
  "NSLocationWhenInUseUsageDescription",
  "NSMicrophoneUsageDescription",
  "NSPhotoLibraryUsageDescription",
  "NSSpeechRecognitionUsageDescription",
  "NSCalendarsFullAccessUsageDescription",
  "NSFaceIDUsageDescription",
]);

const XCODEGEN_MISSING =
  "xcodegen is not installed. Run `brew install xcodegen` once, then call this tool again — " +
  "the project sources are already written, so use mode \"regenerate\" with the same dir.";

const q = (s: string): string => JSON.stringify(s);

const projectYml = (a: Required<Pick<Args, "bundle_id" | "name">> & Args, adopt = false): string => {
  // Adopting an existing folder: the sources ARE the folder, so Info.plist and entitlements sit at its root.
  const prefix = adopt ? "" : `${a.name}/`;
  const sources = adopt
    ? `[{ path: ".", excludes: ["*.xcodeproj/**", "project.yml", "build/**", "*Tests/**"] }]`
    : `[${a.name}]`;
  const display = a.display_name?.trim() || a.name;
  const target = a.deployment_target ?? "17.0";
  const usage = Object.entries(a.usage ?? {})
    .map(([k, v]) => `        ${k}: ${q(v)}`)
    .join("\n");
  const push = a.push
    ? `    entitlements:
      path: ${prefix}${a.name}.entitlements
      properties:
        aps-environment: development
`
    : "";
  const team = a.team_id ? `        DEVELOPMENT_TEAM: ${a.team_id}\n` : "";
  const tests = a.tests
    ? `
  ${a.name}Tests:
    type: bundle.unit-test
    platform: iOS
    sources: [${a.name}Tests]
    dependencies:
      - target: ${a.name}
`
    : "";
  return `# Source of truth for ${a.name}.xcodeproj — edit this, then regenerate (scaffold_ios_app, mode "regenerate").
name: ${a.name}
options:
  bundleIdPrefix: ${a.bundle_id.split(".").slice(0, -1).join(".") || a.bundle_id}
  deploymentTarget:
    iOS: "${target}"
  createIntermediateGroups: true
settings:
  base:
    SWIFT_VERSION: "5.0"
    MARKETING_VERSION: "1.0"
    CURRENT_PROJECT_VERSION: "1"
targets:
  ${a.name}:
    type: application
    platform: iOS
    sources: ${sources}
    settings:
      base:
        PRODUCT_BUNDLE_IDENTIFIER: ${a.bundle_id}
        ASSETCATALOG_COMPILER_APPICON_NAME: AppIcon
        GENERATE_INFOPLIST_FILE: NO
${team}${push}    info:
      path: ${prefix}Info.plist
      properties:
        CFBundleDisplayName: ${q(display)}
        UILaunchScreen: {}
        UISupportedInterfaceOrientations: [UIInterfaceOrientationPortrait, UIInterfaceOrientationLandscapeLeft, UIInterfaceOrientationLandscapeRight]
        ITSAppUsesNonExemptEncryption: false
${usage ? usage + "\n" : ""}${tests}`;
};

const appSwift = (n: string): string => `import SwiftUI

@main
struct ${n}App: App {
    var body: some Scene {
        WindowGroup {
            ContentView()
        }
    }
}
`;

const contentSwift = (n: string): string => `import SwiftUI

struct ContentView: View {
    var body: some View {
        VStack(spacing: 12) {
            Image(systemName: "sparkles")
                .imageScale(.large)
                .foregroundStyle(.tint)
            Text("${n}")
                .font(.title)
        }
        .padding()
    }
}

#Preview {
    ContentView()
}
`;

const testsSwift = (n: string): string => `import XCTest
@testable import ${n}

final class ${n}Tests: XCTestCase {
    func testLaunches() {
        XCTAssertTrue(true)
    }
}
`;

const catalog = {
  accent: `{ "colors" : [ { "idiom" : "universal" } ], "info" : { "author" : "xcode", "version" : 1 } }\n`,
  appIcon: `{ "images" : [ { "idiom" : "universal", "platform" : "ios", "size" : "1024x1024" } ], "info" : { "author" : "xcode", "version" : 1 } }\n`,
  root: `{ "info" : { "author" : "xcode", "version" : 1 } }\n`,
};

const runXcodeGen = (cwd: string): Promise<{ ok: boolean; out: string }> =>
  new Promise((resolve) => {
    // Fixed argv, no shell. `--spec` is relative to cwd and never taken from the model.
    execFile("xcodegen", ["generate", "--spec", "project.yml"], { cwd, timeout: 120_000, maxBuffer: 4_000_000 }, (err: any, stdout, stderr) => {
      if (err && typeof err.code === "string") resolve({ ok: false, out: XCODEGEN_MISSING });
      else resolve({ ok: !err, out: `${stdout}${stderr}`.trim().split("\n").slice(-12).join("\n") });
    });
  });

/** Where the project goes: `dir` if given, else <default folder>/<name>. */
const projectDir = (a: Args): string => resolveArg(a?.dir || a?.name || "");

export const scaffoldIosApp: Tool = {
  name: "scaffold_ios_app",
  description:
    "Create a complete, buildable iOS app project: project.yml, the .xcodeproj, Info.plist, an asset " +
    "catalog, a SwiftUI app + ContentView, and optionally a unit-test target and a push entitlement. " +
    "Give \"name\" (letters/digits, becomes the target and the folder) and \"bundle_id\" " +
    "(e.g. com.example.MyApp). Optional: deployment_target (default \"17.0\"), display_name, team_id " +
    "(10-char Apple team), push (aps-environment), tests (unit-test target), usage (permission prompt " +
    "strings keyed by NSCameraUsageDescription, NSMicrophoneUsageDescription, NSPhotoLibraryUsageDescription, " +
    "NSLocationWhenInUseUsageDescription, NSContactsUsageDescription, NSFaceIDUsageDescription, " +
    "NSSpeechRecognitionUsageDescription, NSCalendarsFullAccessUsageDescription). Refuses a folder that " +
    "already holds a project. Afterwards add Swift with write_file under <name>/<name>/, and to add files " +
    "outside that folder, targets or settings edit project.yml with edit_file, then call this tool with " +
    "mode \"regenerate\" and \"dir\" to rebuild the .xcodeproj. To bring an EXISTING folder of loose Swift " +
    "files under a project, use mode \"adopt\" with \"dir\", \"name\" and \"bundle_id\" (existing files are " +
    "never touched; it only adds project.yml, an asset catalog if missing, and the .xcodeproj). Build with run_command if the repo declares " +
    "an xcodebuild command. Requires XcodeGen (brew install xcodegen).",
  argsSchema:
    '{ "name": string, "bundle_id": string, "dir"?: string, "deployment_target"?: string, "display_name"?: string, ' +
    '"team_id"?: string, "push"?: boolean, "tests"?: boolean, "usage"?: object, "mode"?: "create" | "adopt" | "regenerate" }',
  classify: (a: Args): ClassifiedAction => {
    const dir = a?.mode === "regenerate" || a?.mode === "adopt" ? resolveArg(a?.dir) : projectDir(a);
    return {
      reversibility: "reversible",
      summary: `${a?.mode === "regenerate" ? "Regenerate Xcode project in" : a?.mode === "adopt" ? "Wrap existing Swift files in an Xcode project:" : "Scaffold iOS app in new folder"} ${dir || "(no path)"}`,
      target: dir,
    };
  },
  checkPolicy: (policy: Policy, a: Args): PolicyDecision => {
    if (a?.mode === "regenerate") {
      const dir = resolveArg(a?.dir);
      const g = textTargetGate(policy, dir, { ext: false });
      if (!g.allowed) return g;
      if (!fs.existsSync(path.join(dir, "project.yml"))) {
        return { allowed: false, reason: `${dir} has no project.yml; create the project first.` };
      }
      return g;
    }
    if (!NAME.test(String(a?.name ?? ""))) {
      return { allowed: false, reason: '"name" must be letters and digits only, starting with a letter (max 40).' };
    }
    if (!BUNDLE.test(String(a?.bundle_id ?? ""))) {
      return { allowed: false, reason: '"bundle_id" must look like com.example.MyApp.' };
    }
    if (a.deployment_target != null && !TARGET.test(String(a.deployment_target))) {
      return { allowed: false, reason: '"deployment_target" must look like "17.0".' };
    }
    if (a.team_id != null && !TEAM.test(String(a.team_id))) {
      return { allowed: false, reason: '"team_id" must be the 10-character Apple team id.' };
    }
    for (const [k, v] of Object.entries(a.usage ?? {})) {
      if (!USAGE_KEYS.has(k)) return { allowed: false, reason: `usage key ${k} is not allowed. Allowed: ${[...USAGE_KEYS].join(", ")}.` };
      if (typeof v !== "string" || !v.trim() || v.length > 300) return { allowed: false, reason: `usage ${k} must be 1-300 characters.` };
    }
    const dir = a?.mode === "adopt" ? resolveArg(a?.dir) : projectDir(a);
    const g = textTargetGate(policy, dir, { ext: false });
    if (!g.allowed) return g;
    if (a?.mode === "adopt" && !(fs.existsSync(dir) && fs.readdirSync(dir).some((f) => f.endsWith(".swift")))) {
      return { allowed: false, reason: `${dir} holds no .swift files to adopt.` };
    }
    if (fs.existsSync(path.join(dir, "project.yml")) || (fs.existsSync(dir) && fs.readdirSync(dir).some((f) => f.endsWith(".xcodeproj")))) {
      return { allowed: false, reason: `${dir} already holds an Xcode project. Edit project.yml and use mode "regenerate", or pick a new name.` };
    }
    return g;
  },
  run: async (a: Args, ctx) => {
    try {
      if (a?.mode === "regenerate") {
        const dir = resolveArg(a?.dir);
        const r = await runXcodeGen(dir);
        if (r.ok) recordDeliverable(path.join(dir, "project.yml"), "edit", ctx?.runId);
        return r.ok ? `Regenerated the Xcode project in ${dir}\n${r.out}` : `ERROR: xcodegen failed in ${dir}\n${r.out}`;
      }
      if (a?.mode === "adopt") {
        const n = String(a.name);
        const dir = resolveArg(a?.dir);
        const files: Record<string, string> = { "project.yml": projectYml({ ...a, bundle_id: String(a.bundle_id), name: n }, true) };
        // Only fill gaps: an existing catalog is the user's, and is left exactly as it is.
        const cat = path.join(dir, "Assets.xcassets");
        if (!fs.existsSync(cat)) {
          files["Assets.xcassets/Contents.json"] = catalog.root;
          files["Assets.xcassets/AccentColor.colorset/Contents.json"] = catalog.accent;
          files["Assets.xcassets/AppIcon.appiconset/Contents.json"] = catalog.appIcon;
        }
        for (const [rel, text] of Object.entries(files)) {
          const target = path.join(dir, rel);
          fs.mkdirSync(path.dirname(target), { recursive: true });
          fs.writeFileSync(target, text, "utf8");
          recordDeliverable(target, "create", ctx?.runId);
        }
        const r = await runXcodeGen(dir);
        return r.ok
          ? `Adopted ${dir} as ${n}: wrote ${Object.keys(files).join(", ")} and generated ${n}.xcodeproj. Existing files were not modified.\n${r.out}`
          : `ERROR: wrote ${Object.keys(files).join(", ")} in ${dir} but the project was not generated.\n${r.out}`;
      }
      const n = String(a.name);
      const dir = projectDir(a);
      const files: Record<string, string> = {
        "project.yml": projectYml({ ...a, bundle_id: String(a.bundle_id), name: n }),
        [`${n}/${n}App.swift`]: appSwift(n),
        [`${n}/ContentView.swift`]: contentSwift(n),
        [`${n}/Assets.xcassets/Contents.json`]: catalog.root,
        [`${n}/Assets.xcassets/AccentColor.colorset/Contents.json`]: catalog.accent,
        [`${n}/Assets.xcassets/AppIcon.appiconset/Contents.json`]: catalog.appIcon,
      };
      if (a.tests) files[`${n}Tests/${n}Tests.swift`] = testsSwift(n);
      for (const [rel, text] of Object.entries(files)) {
        const target = path.join(dir, rel);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, text, "utf8");
        recordDeliverable(target, "create", ctx?.runId);
      }
      const r = await runXcodeGen(dir);
      const list = Object.keys(files).join(", ");
      if (!r.ok) return `ERROR: sources written to ${dir} (${list}) but the project was not generated.\n${r.out}`;
      return (
        `Created ${n} in ${dir}\nFiles: ${list}\nGenerated ${n}.xcodeproj, with Info.plist` +
        `${a.push ? " and entitlements" : ""} produced from project.yml.\n` +
        `Add more Swift under ${dir}/${n}/ — new files are picked up on the next "regenerate". ` +
        `The app icon is an empty 1024px slot; supply an AppIcon.png before shipping.\n${r.out}`
      );
    } catch (err) {
      return `ERROR: ${err instanceof Error ? err.message : String(err)}`;
    }
  },
};
